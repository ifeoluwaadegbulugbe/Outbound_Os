"use client";

import { useRouter } from "next/navigation";
import { useTransition } from "react";
import { Sparkles, RefreshCw, CircleHelp, CheckCircle2, Lightbulb } from "lucide-react";
import { Panel, Badge } from "@/components/ui/display";
import { Button } from "@/components/ui/button";
import { toast } from "@/components/ui/toast";
import { MESSAGE_ANGLES, VALUE_PROPS } from "@/server/domain/taxonomy";
import { timeAgo } from "@/lib/utils";
import { researchAction } from "./actions";

interface Research {
  summary: string;
  statements: { statements: { text: string; kind: string; basis: string[] }[]; facts: { id: string; text: string; source: string }[]; unknowns: string[] };
  why_relevant: string[];
  recommended_angle: string | null;
  value_props: string[];
  confidence: number;
  generator: string;
  created_at: Date;
}

export function ResearchPanel({ prospectId, research, canEdit }: { prospectId: string; research: Research | null; canEdit: boolean }) {
  const router = useRouter();
  const [pending, start] = useTransition();
  const run = () =>
    start(async () => {
      const r = await researchAction(prospectId);
      if (r.ok) toast(r.message ?? "Done");
      else toast.error(r.error);
      router.refresh();
    });
  const factById = new Map(research?.statements.facts.map((f) => [f.id, f]) ?? []);

  return (
    <Panel
      title={<span className="inline-flex items-center gap-1.5"><Sparkles className="size-3.5 text-accent" /> AI brief</span>}
      description={research ? `${research.generator === "rules" ? "Built from facts (no AI provider configured)" : `Generated by ${research.generator.replace("ai:", "")}`} · ${timeAgo(research.created_at)}` : "Grounded only in the data we hold"}
      actions={canEdit ? <Button size="xs" variant="ghost" onClick={run} loading={pending}><RefreshCw /> {research ? "Refresh" : "Generate brief"}</Button> : null}
    >
      {!research ? (
        <p className="text-[12.5px] text-fg-3">No brief yet. {canEdit ? "Generate one — it only uses facts on record and labels anything inferred." : ""}</p>
      ) : (
        <div className="space-y-4">
          <p className="text-[13.5px] leading-relaxed text-fg">{research.summary}</p>
          <div className="grid gap-4 md:grid-cols-2">
            <div>
              <h3 className="mb-1.5 text-[11.5px] font-medium uppercase tracking-wide text-fg-3">What we know</h3>
              <ul className="space-y-1.5">
                {research.statements.statements.map((s, i) => (
                  <li key={i} className="flex gap-2 text-[12.5px]">
                    {s.kind === "fact" ? <CheckCircle2 className="mt-0.5 size-3.5 shrink-0 text-success" /> : <Lightbulb className="mt-0.5 size-3.5 shrink-0 text-warning" />}
                    <span>
                      {s.text}
                      {s.kind === "inference" ? <Badge tone="warning" className="ml-1.5 h-4 px-1 text-[10px]">AI inference</Badge> : null}
                      <span className="ml-1 text-[11px] text-fg-3" title={s.basis.map((b) => factById.get(b)?.text ?? b).join("\n")}>[{s.basis.join(", ")}]</span>
                    </span>
                  </li>
                ))}
              </ul>
            </div>
            <div className="space-y-3">
              <div>
                <h3 className="mb-1.5 text-[11.5px] font-medium uppercase tracking-wide text-fg-3">Why Orbit could be relevant</h3>
                <ul className="list-disc space-y-1 pl-4 text-[12.5px]">{research.why_relevant.map((w) => <li key={w}>{w}</li>)}</ul>
              </div>
              <div className="flex flex-wrap items-center gap-1.5 text-[12px]">
                <span className="text-fg-3">Recommended angle:</span>
                <Badge tone="accent">{MESSAGE_ANGLES.find((a) => a.key === research.recommended_angle)?.label ?? research.recommended_angle}</Badge>
                {research.value_props.map((v) => <Badge key={v}>{VALUE_PROPS[v as keyof typeof VALUE_PROPS]?.label ?? v}</Badge>)}
              </div>
              <p className="text-[12px] text-fg-3">Confidence {research.confidence}% (based on how much evidence we have)</p>
            </div>
          </div>
          {research.statements.unknowns.length ? (
            <div className="rounded-md bg-surface-2 px-3 py-2">
              <p className="flex items-center gap-1.5 text-[11.5px] font-medium text-fg-3"><CircleHelp className="size-3.5" /> Unknown — not assumed</p>
              <p className="mt-0.5 text-[12px] text-fg-2">{research.statements.unknowns.join(" · ")}</p>
            </div>
          ) : null}
        </div>
      )}
    </Panel>
  );
}
